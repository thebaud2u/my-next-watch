			<h2 class="mb-4 text-xl font-semibold">3. GESTION DES DROITS DES PERSONNES</h2>
			<h3 class="mb-4 text-lg font-semibold pl-6">3.1 DROIT D'ACCÈS</h3>
			<p class="mb-4">
				Les Personnes concernées disposent du droit d'obtenir du Responsable de traitement la confirmation que leurs Données sont traitées et bénéficie d'un droit d'accès leur permettant d'être informé des finalités du traitement, des catégories de Données collectées, des destinataires ou catégories de destinataires auxquels les Données ont été ou seront communiquées, de la durée de conservation des Données envisagée, de l’existence des autres droits et de la possibilité de saisir la CNIL.
			</p>

			<h3 class="mb-4 text-lg font-semibold pl-6">3.2 DROIT DE RECTIFICATION</h3>
			<p class="mb-4">
				Les Personnes concernées disposent du droit de demander la rectification des Données qui seraient obsolètes ou erronées.
			</p>

			<h3 class="mb-4 text-lg font-semibold pl-6">3.3 DROIT À L'EFFACEMENT</h3>
			<p class="mb-4">
				Les Personnes concernées ont la possibilité d'obtenir l'effacement, dans les meilleurs délais, de leurs Données lorsque l'un des motifs suivants s'applique :
			</p>
			<ul class="mb-4 list-disc list-inside">
				<li>les Données ne sont plus nécessaires au regard des finalités pour lesquelles elles ont été collectées ou traitées d'une autre manière par le Responsable de traitement ;</li>
				<li>les Personnes concernées ont retiré leur consentement pour le traitement de leurs Données et il n'existe pas d'autre fondement juridique au traitement ;</li>
				<li>les Personnes concernées exercent leur droit d'opposition dans les conditions rappelées ci-après et il n'existe pas de motif légitime impérieux pour le traitement ;</li>
				<li>les Données ont fait l'objet d'un traitement illicite ;</li>
				<li>les Données doivent être effacées pour respecter une obligation légale.</li>
			</ul>

			<h3 class="mb-4 text-lg font-semibold pl-6">3.4 DROIT A LA LIMITATION</h3>
			<p class="mb-4">
				Les Personnes concernées ont la possibilité d'obtenir la limitation du traitement de leurs Données lorsque l'un des motifs suivants s'applique :
			</p>
			<ul class="mb-4 list-disc list-inside">
				<li>les Données sont inexactes,</li>
				<li>le traitement est illicite ;</li>
				<li>le Responsable de traitement n'a plus besoin de ces Données aux fins du traitement, mais celles-ci demeurent encore nécessaires pour la constatation, l'exercice ou la défense de droits en justice.</li>
			</ul>

			<h3 class="mb-4 text-lg font-semibold pl-6">3.5 DROIT À LA PORTABILITÉ</h3>
			<p class="mb-4">
				Les Personnes concernées ont la possibilité de recevoir leurs Données, dans un format structuré, couramment utilisé et lisible par machine lorsque :
			</p>
			<ul class="mb-4 list-disc list-inside">
				<li>le traitement de leurs Données est fondé sur le consentement, ou sur un contrat ;</li>
				<li>le traitement est effectué à l'aide de procédés automatisés</li>
			</ul>

			<h3 class="mb-4 text-lg font-semibold pl-6">3.6 DROIT D’OPPOSITION</h3>
			<p class="mb-4">
				Les Personnes concernées ont le droit de s'opposer à tout moment, pour des raisons tenant à leur situation particulière, à un traitement de ses Données fondé sur son intérêt légitime.
			</p>

