			<h2 class="mb-4 text-xl font-semibold">4. DISPOSITIONS COMPLÉMENTAIRES</h2>
			<h3 class="mb-4 text-lg font-semibold pl-6">4.1 DROIT D'ACCÈS</h3>
			<p class="mb-4">
