			<p class="mb-4">Nous nous engageons à fournir à la CNIL, à première demande, les renseignements lui permettant de vérifier la conformité des traitements à la réglementation en vigueur.</p>

			<h3 class="mb-4 text-lg font-semibold pl-6">4.3 MESURES DE SÉCURITÉ</h3>
			<p class="mb-4">Nous mettons en œuvre les mesures de sécurité techniques, physiques ou logiques que nous estimons appropriées pour lutter contre la destruction, la perte, l’altération ou la divulgation non autorisée des Données de manière accidentelle ou illicite.</p>
			<p class="mb-4">En tout état de cause, nous nous engageons, en cas de changement des moyens visant à assurer la sécurité et la confidentialité des Données à caractère personnel, à les remplacer par des moyens d’une performance supérieure. Aucune évolution ne pourra conduire à une régression du niveau de sécurité.</p>

			<h3 class="mb-4 text-lg font-semibold pl-6">4.4 VIOLATION DE DONNÉES</h3>
			<p class="mb-4">Nous nous engageons à notifier à la CNIL toute violation de données que nous pourrions subir dans les conditions prescrites par la réglementation en matière de données à caractère personnel.</p>
